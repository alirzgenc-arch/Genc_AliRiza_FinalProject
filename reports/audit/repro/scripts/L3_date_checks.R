# Independent date/leakage checks on the REBUILT development frame. Prints counts/flags only.
mf <- read.csv("data/processed/model_frame_monthly.csv", stringsAsFactors = FALSE)
mq <- read.csv("reports/qa/music_feature_qa.csv", stringsAsFactors = FALSE)
cis <- read.csv("data/processed/cis_vox_verified.csv", colClasses = c(study_id = "character"))
rd <- read.csv("data/metadata/cis_release_dates.csv", colClasses = "character")
for (v in c("origin", "win_start", "win_end", "target_mature_at")) mf[[v]] <- as.Date(mf[[v]])
add_m <- function(d, k) as.Date(sapply(d, function(x) seq(as.Date(format(x, "%Y-%m-01")), by = "month", length.out = k + 1)[k + 1]))
r <- list()
r$origin_on_10th      <- all(format(mf$origin, "%d") == "10")
r$win_start_10th_m1   <- all(mf$win_start == add_m(mf$origin, 1) + 9)
r$win_end_10th_m2     <- all(mf$win_end == add_m(mf$origin, 2) + 9)
r$mature_after_window <- all(mf$target_mature_at >= mf$win_end)
r$poll_age_ge_1_day   <- all(mf$poll_age_days[mf$features_ok] >= 1)
# recompute release dates -> as-of poll inputs independently (dates only)
rel <- as.Date(rd$advance_date[match(cis$study_id, rd$study_id)])
asof_n <- vapply(mf$origin, function(t) sum(rel + 1 <= t), 0)
r$n_prior_releases_match <- all(asof_n == mf$n_prior_releases)
tgt_n <- mapply(function(a, b) sum(rel >= a & rel < b), mf$win_start, mf$win_end)
r$n_target_releases_match <- all(tgt_n == mf$n_target_releases)
r$august_windows_empty <- all(mf$n_target_releases[format(mf$win_start, "%m") == "08"] == 0)
r$dropped_cases <- paste(format(mf$origin[!mf$common_case], "%Y-%m"), collapse = ",")
# music alignment: month m-1, available by origin, complete, no NA
mq$origin <- as.Date(mq$origin)
prev_month <- function(d) format(seq(as.Date(format(d, "%Y-%m-01")), by = "-1 month", length.out = 2)[2], "%Y-%m")
r$music_month_is_m_minus_1 <- all(mapply(function(m, o) m == prev_month(o), mq$month_m1, mq$origin))
r$music_available_by_origin <- all(mq$available_by_origin)
r$music_complete_and_not_na <- all(mq$complete) && !any(mq$value_is_na)
r$music_origins_match_frame <- setequal(unique(mq$origin), mf$origin)
r$target_not_in_predictors <- !any(grepl("target", c("poll_level", "poll_change", "poll_age_days", grep("^music_", names(mf), value = TRUE))))
for (n in names(r)) cat(sprintf("%-28s %s\n", n, r[[n]]))
